public class arithmetic {
    public static void main(String args[])
    {
        int x=10;
        int y=5;
        //Addition
        int z1=x+y;
        //Subtraction
        int z2=x-y;
        //Multiplication
        int z3=x*y;
        //division
        int z4=x/y;
        //modulus
        int z5=x%y;
        System.out.println("Addition:" +z1);
        System.out.println("Subtraction: " +z2);
        System.out.println("Multiplication: " +z3);
        System.out.println("Division: " +z4);
        System.out.println("Modulus: " +z5);
    }
    
}
